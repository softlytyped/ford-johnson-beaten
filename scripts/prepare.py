#!/usr/bin/env python3
"""Prepare Lean constants from the pinned certificate archives."""

import gzip
import hashlib
import json
from io import BytesIO
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
LABEL_BASE = ord("A")


def verify_sha256(data: bytes, expected: str, description: str) -> None:
    actual = hashlib.sha256(data).hexdigest()
    
    if actual != expected:
        raise ValueError(f"{description}: expected SHA-256 {expected}, got {actual}")


def encode_tree(archive: bytes) -> bytes:
    encoded = bytearray()
    
    with gzip.GzipFile(fileobj=BytesIO(archive)) as nodes:
        for node in nodes:
            match node.split():
                case [b"."]:
                    encoded.extend(b".")
                case [x, y]:
                    encoded.extend((LABEL_BASE + int(x), LABEL_BASE + int(y)))
                case _:
                    raise ValueError(f"Invalid tree node: {node!r}")
                    
    return bytes(encoded)


def render_module(name: str, encoded: bytes) -> str:
    literal = json.dumps(encoded.decode("ascii"))
    
    return f"""-- Generated by scripts/prepare.py.
namespace FordJohnson.Data

def {name} : String := {literal}

end FordJohnson.Data
"""


def write_if_changed(path: Path, source: str) -> None:
    content = source.encode("utf-8")
    
    if path.exists() and path.read_bytes() == content:
        return

    path.parent.mkdir(parents=True, exist_ok=True)
    
    temporary = path.with_name(f".{path.name}.tmp")
    temporary.write_bytes(content)
    temporary.replace(path)


def prepare_certificate(name: str, module: str, hashes: dict[str, str]) -> None:
    archive_path = ROOT / "FordJohnson" / "Data" / f"{name}.tree.gz"
    archive = archive_path.read_bytes()
    verify_sha256(archive, hashes["sha256"], archive_path.name)

    encoded = encode_tree(archive)
    verify_sha256(encoded, hashes["encoded_sha256"], f"{name} encoding")

    module_path = ROOT / "FordJohnson" / "Data" / f"{module}.lean"
    write_if_changed(module_path, render_module(name, encoded))


def main() -> None:
    manifest_path = ROOT / "FordJohnson" / "Data" / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    
    for name, module in (("t21_5", "T21"), ("t42_4", "T42")):
        prepare_certificate(name, module, manifest[name])
        print(f"{name}: prepared", flush=True)


if __name__ == "__main__":
    main()
